#!/usr/bin/env python3
"""Turn a PNG into a static LVGL RGB888 image descriptor.

The recovery splash is one full-screen still, so the generated file is a
single lv_image_dsc_t whose pixels live in .rodata. No decoder, no heap and
no runtime file access are involved: lv_image draws the bytes directly.

Pure standard library on purpose: the AOSP build host has python3 but not
necessarily Pillow or pypng.
"""

import argparse
import struct
import sys
import zlib

CHUNK = 512          # bytes emitted per string literal
BYTES_PER_LINE = 64  # hex bytes per source line


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s: not a PNG" % path)

    pos = 8
    width = height = depth = ctype = interlace = 0
    idat = b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", chunk)
        elif kind == b"IDAT":
            idat += chunk
        elif kind == b"IEND":
            break
        pos += 12 + length

    if depth != 8 or interlace != 0 or ctype not in (2, 6):
        raise SystemExit("%s: need an 8-bit RGB or RGBA PNG (got depth %d, color type %d)"
                         % (path, depth, ctype))

    bpp = 3 if ctype == 2 else 4
    raw = zlib.decompress(idat)
    stride = width * bpp
    out = bytearray(width * height * 3)
    prev = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind = raw[start]
        line = bytearray(raw[start + 1:start + 1 + stride])
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if kind == 1:
                line[x] = (line[x] + a) & 255
            elif kind == 2:
                line[x] = (line[x] + b) & 255
            elif kind == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        dst = y * width * 3
        if bpp == 3:
            out[dst:dst + width * 3] = line
        else:
            for i in range(width):
                out[dst + i * 3: dst + i * 3 + 3] = line[i * 4: i * 4 + 3]
        # LVGL stores RGB888 as B, G, R in memory (lv_color_t is blue-green-red),
        # so the bytes have to be reordered or red and blue come out swapped.
        out[dst:dst + width * 3:3], out[dst + 2:dst + width * 3:3] = \
            out[dst + 2:dst + width * 3:3], out[dst:dst + width * 3:3]
        prev = line
    return width, height, bytes(out)


def emit(pixels, width, height, name, stream):
    stream.write("// Generated by gen_splash_bg.py from %s.png. Do not edit.\n" % name)
    stream.write('#include "image/%s.h"\n\n' % name)
    stream.write("static const unsigned char %s_pixels[] =\n" % name)
    for base in range(0, len(pixels), CHUNK):
        piece = pixels[base:base + CHUNK]
        stream.write('"')
        for i in range(0, len(piece), BYTES_PER_LINE):
            row = piece[i:i + BYTES_PER_LINE]
            stream.write("".join("\\x%02x" % value for value in row))
        stream.write('"\n')
    stream.write(";\n\n")
    stream.write("const lv_image_dsc_t %s = {\n" % name)
    stream.write("    .header.magic = LV_IMAGE_HEADER_MAGIC,\n")
    stream.write("    .header.cf = LV_COLOR_FORMAT_RGB888,\n")
    stream.write("    .header.flags = 0,\n")
    stream.write("    .header.w = %d,\n" % width)
    stream.write("    .header.h = %d,\n" % height)
    stream.write("    .header.stride = %d,\n" % (width * 3))
    stream.write("    .data_size = sizeof(%s_pixels) - 1,  // drop the string terminator\n" % name)
    stream.write("    .data = %s_pixels,\n" % name)
    stream.write("};\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("png")
    parser.add_argument("--name", default="splash_bg")
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()

    width, height, pixels = read_png(args.png)
    with open(args.output, "w", newline="\n") as stream:
        emit(pixels, width, height, args.name, stream)
    print("%s: %dx%d, %d bytes" % (args.output, width, height, len(pixels)), file=sys.stderr)


if __name__ == "__main__":
    main()
